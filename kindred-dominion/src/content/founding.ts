const E = (x: number, y = 0, amount = 1): Influence => ({
  x,
  y,
  amount,
  mechanic: "expansion",
});
const F = (x: number, y = 0, amount = 1): Influence => ({
  x,
  y,
  amount,
  mechanic: "fortification",
});
const O = (x: number, y = 0, amount = 1): Influence => ({
  x,
  y,
  amount,
  mechanic: "overthrow",
});
const self: Target = { kind: "self" },
  friendly: Target = { kind: "all", relation: "friendly" },
  enemy: Target = { kind: "all", relation: "enemy" };
const pattern = (
  offsets: [number, number][],
  relation: Target["relation"] = "any",
): Target => ({
  kind: "pattern",
  relation,
  offsets: offsets.map(([x, y]) => ({ x, y })),
});
const front = pattern([[1, 0]], "enemy");
const power = (amount: number, target: Target = self): Effect => ({
  type: "power",
  amount,
  target,
});
const tokens = (amount: number, target: Target = self): Effect => ({
  type: "tokens",
  amount,
  target,
});
const fortify = (amount: number, target: Target = self): Effect => ({
  type: "fortify",
  amount,
  target,
});
const draw = (amount = 1): Effect => ({ type: "draw", amount });
const generate = (card: string, amount = 1): Effect => ({
  type: "generate",
  card,
  amount,
});
const kill = (target: Target = front): Effect => ({ type: "destroy", target });
const ward = (
  target: Target = self,
  protection: "weakening" | "destruction" = "weakening",
): Effect => ({ type: "protect", target, protection });
type DraftAbility = Omit<Ability, "id">;
const a = (
  trigger: Ability["trigger"],
  effects: Effect[],
  extras: Partial<DraftAbility> = {},
): DraftAbility => ({
  trigger,
  effects,
  limit: { perEvent: 1, perMatch: 1 },
  ...extras,
});
type Draft = Omit<
  CardDefinition,
  "kindred" | "glyph" | "abilities" | "text" | "type" | "tags"
> & {
  type?: CardDefinition["type"];
  tags?: string[];
  abilities?: DraftAbility[];
};
function collection(
  kindred: string,
  glyph: string,
  cards: Draft[],
): CardDefinition[] {
  return cards.map((c) => {
    const result: CardDefinition = {
      type: "standard",
      tags: [kindred.toLowerCase(), ...(c.tags ?? [])],
      ...c,
      kindred,
      glyph,
      abilities: (c.abilities ?? []).map((ability, i) => ({
        ...ability,
        id: `${c.id}-ability-${i + 1}`,
      })),
      text: "",
    };
    result.tags = [kindred.toLowerCase(), ...(c.tags ?? [])];
    result.text = [
      ...c.influence.map(
        (e) => `${e.mechanic} ${e.amount} at ${e.x} forward, ${e.y} down.`,
      ),
      ...(result.prerequisite
        ? [
            `Requires ${result.prerequisite.definitions?.join(" or ") ?? result.prerequisite.tags?.map((t) => `classification ${t}`).join(" or ") ?? "a matching creature"}${result.prerequisite.minPower !== undefined ? `, at least ${result.prerequisite.minPower} power` : ""}.`,
          ]
        : []),
      ...result.abilities.map(describeAbility),
    ].join(" ");
    return result;
  });
}
